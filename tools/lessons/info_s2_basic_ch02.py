SUM = """
int s = 0;
for (int i = 0; i < n; i++)
    s += a[i];        // 불변식: 반복 i가 시작할 때 s = a[0] + … + a[i-1]
"""

MAXLOOP = """
int m = a[0];
for (int i = 1; i < n; i++)
    if (a[i] > m) m = a[i];   // 불변식: 반복 i가 시작할 때 m = max(a[0..i-1])
"""

INSERTION = """
for (int i = 1; i < n; i++) {        // 불변식: a[0..i-1]은 정렬되어 있다
    int key = a[i], j = i - 1;
    while (j >= 0 && a[j] > key) {
        a[j + 1] = a[j];             // 한 칸 밀기
        j--;
    }
    a[j + 1] = key;
}
"""

LOMUTO = """
// 마지막 원소 p를 기준으로 나누기
int p = a[n - 1], i = -1;
for (int j = 0; j < n - 1; j++)      // 불변식: a[0..i] ≤ p, a[i+1..j-1] > p
    if (a[j] <= p) swap(a[++i], a[j]);
swap(a[i + 1], a[n - 1]);            // 기준은 i + 1번 자리로
"""

GCD = """
int cnt = 0;
while (b != 0) {          // 불변식: gcd(a, b)는 처음 값의 최대공약수와 같다
    int r = a % b;
    a = b; b = r;
    cnt++;
}
// 답은 a
"""

FASTPOW = """
long long r = 1, x = a, e = n;
int cnt = 0;
while (e > 0) {           // 불변식: r · xᵉ = aⁿ
    if (e % 2 == 1) r *= x;
    x *= x; e /= 2;
    cnt++;
}
// 답은 r
"""

HANOI = """
// n개의 원판을 from에서 to로 옮긴다 (via를 거쳐서)
void hanoi(int n, int from, int via, int to) {
    if (n == 0) return;
    hanoi(n - 1, from, to, via);
    move(from, to);                  // 가장 큰 원판 하나 옮기기
    hanoi(n - 1, via, from, to);
}
"""

FIBREC = """
int fib(int n) {
    if (n <= 1) return n;
    return fib(n - 1) + fib(n - 2);
}
"""

POWREC = """
long long pw(long long x, int n) {
    if (n == 0) return 1;
    long long h = pw(x, n / 2);
    return (n % 2 == 0) ? h * h : h * h * x;
}
"""

MSORT = """
void msort(int l, int r) {           // a[l..r-1]을 정렬
    if (r - l <= 1) return;
    int m = (l + r) / 2;
    msort(l, m); msort(m, r);
    merge(l, m, r);                  // 정렬된 두 부분을 합친다
}
"""

