def _strong(v):
    """0.1 M HCl 50 mL에 0.1 M NaOH v mL를 넣었을 때의 pH."""
    h = (0.1 * 50 - 0.1 * v) / (50 + v)
    if abs(h) < 1e-7:
        return 7.0
    return -math.log10(h) if h > 0 else 14 + math.log10(-h)


def _weak(v):
    """0.2 M HA(pKa 5) 50 mL에 0.2 M NaOH v mL를 넣었을 때의 pH."""
    ka, na, nb, vt = 1e-5, 0.2 * 50, 0.2 * v, (50 + v) / 1000
    if v == 0:
        return -math.log10(math.sqrt(ka * 0.2))
    if nb < na - 1e-9:
        return 5 + math.log10(nb / (na - nb))
    if abs(nb - na) < 1e-9:
        return 14 + math.log10(math.sqrt(1e-9 * na / 1000 / vt))
    return 14 + math.log10((nb - na) / 1000 / vt)


