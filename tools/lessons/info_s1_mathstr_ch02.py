GCD = """
long long gcd(long long a, long long b) {
    while (b != 0) {               // 이 반복이 몇 번 도는가
        long long r = a % b;
        a = b; b = r;
    }
    return a;
}
"""
LCM = """
long long lcm(long long a, long long b) {
    return a / gcd(a, b) * b;      // 먼저 나눈 뒤 곱해 넘침을 줄인다
}
"""
