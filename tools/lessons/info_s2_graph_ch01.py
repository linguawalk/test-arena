PRIM = """
// 정점 s에서 출발해 트리를 키운다
priority_queue<pair<int,int>, vector<pair<int,int>>, greater<>> pq;   // (w, v), 작은 w부터
pq.push({0, s});
long long total = 0;
while (!pq.empty()) {
    auto [w, v] = pq.top(); pq.pop();
    if (inTree[v]) continue;                   // 이미 트리에 있으면 버린다
    inTree[v] = true; total += w;              // v를 트리에 넣는다
    for (auto [u, c] : adj[v])
        if (!inTree[u]) pq.push({c, u});
}
"""

