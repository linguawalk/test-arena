KAHN = """
// 진입 차수가 0인 정점부터 꺼낸다 (칸 알고리즘)
queue<int> q;
for (int v = 1; v <= n; v++) if (indeg[v] == 0) q.push(v);
vector<int> order;
while (!q.empty()) {
    int u = q.front(); q.pop();
    order.push_back(u);
    for (int v : adj[u])
        if (--indeg[v] == 0) q.push(v);   // 선행 정점이 모두 처리되면 넣는다
}
// order.size() < n 이면 사이클이 있다
"""

KAHNPQ = """
// 번호가 가장 작은 것부터: 큐 대신 최소 힙
priority_queue<int, vector<int>, greater<int>> q;
for (int v = 1; v <= n; v++) if (indeg[v] == 0) q.push(v);
while (!q.empty()) {
    int u = q.top(); q.pop();
    order.push_back(u);
    for (int v : adj[u])
        if (--indeg[v] == 0) q.push(v);
}
"""

