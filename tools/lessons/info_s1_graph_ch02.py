BFS = """
// 시작 정점 s에서 BFS. dist[v]: s에서 v까지 간선 수 (-1이면 아직 방문 안 함)
queue<int> q;
fill(dist, dist + n + 1, -1);
dist[s] = 0; q.push(s);
while (!q.empty()) {
    int u = q.front(); q.pop();          // 방문 순서
    for (int v : adj[u])                 // adj[u]는 번호 오름차순
        if (dist[v] == -1) {
            dist[v] = dist[u] + 1;       // 넣을 때 표시한다
            q.push(v);
        }
}
"""
DFS = """
bool visited[100001];
void dfs(int u) {
    visited[u] = true;                   // 방문 순서
    for (int v : adj[u])                 // adj[u]는 번호 오름차순
        if (!visited[v]) dfs(v);
}
"""
