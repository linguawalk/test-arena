def _batt_v(x, y, y0, y1, label=None):
    """세로 도선 (x, y0)~(x, y1) 가운데 (x, y)에 전지. 긴 판이 위쪽(+)."""
    els = [seg((x, y0), (x, y - 0.15)), seg((x, y + 0.15), (x, y1)),
           seg((x - 0.4, y + 0.15), (x + 0.4, y + 0.15)), seg((x - 0.2, y - 0.15), (x + 0.2, y - 0.15))]
    if label:
        els.append(tx((x - 0.9, y), label))
    return els


def _cap_v(x, y, y0, y1, label=None):
    els = [seg((x, y0), (x, y - 0.15)), seg((x, y + 0.15), (x, y1)),
           seg((x - 0.4, y + 0.15), (x + 0.4, y + 0.15)), seg((x - 0.4, y - 0.15), (x + 0.4, y - 0.15))]
    if label:
        els.append(tx((x + 0.95, y), label))
    return els


