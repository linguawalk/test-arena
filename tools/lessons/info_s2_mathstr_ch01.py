def _grid(w, h, path, alt, diag=False):
    els = [seg((x, 0), (x, h)) for x in range(w + 1)] + [seg((0, y), (w, y)) for y in range(h + 1)]
    if diag:
        els.append(seg((0, 0), (min(w, h), min(w, h)), dash=True))
    els += [seg(path[i], path[i + 1], hl=True) for i in range(len(path) - 1)]
    els += [pt((0, 0), "S", "sw"), pt((w, h), "T", "ne")]
    return G(alt, *els, maxh=220)


