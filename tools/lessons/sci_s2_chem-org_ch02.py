def _smooth(keys):
    """키 포인트 사이를 코사인 보간해 매끄러운 에너지 곡선을 만든다(키 포인트가 극값)."""
    out = []
    for i in range(0, 101):
        x = i * 0.1
        for (x0, y0), (x1, y1) in zip(keys, keys[1:]):
            if x0 <= x <= x1:
                t = (1 - math.cos(math.pi * (x - x0) / (x1 - x0))) / 2
                out.append((round(x, 2), round(y0 + (y1 - y0) * t, 2)))
                break
    return out


