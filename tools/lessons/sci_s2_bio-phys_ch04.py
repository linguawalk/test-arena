def _bar(y, spans, label):
    """spans: (start, end, dark) 시간 구간."""
    els = [tx((-2.2, y + 0.5), label)]
    for a, b, dark in spans:
        els.append(poly([(a, y), (b, y), (b, y + 1), (a, y + 1)], fill=dark, hl=dark))
    return els


