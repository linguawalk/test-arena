MERGE = """
// 정렬된 a[l..m-1]과 a[m..r-1]을 합치며 역순 쌍을 센다
long long merge(int l, int m, int r) {
    long long inv = 0; int i = l, j = m, k = 0;
    while (i < m && j < r) {
        if (a[i] <= a[j]) tmp[k++] = a[i++];   // 비교 한 번
        else {
            tmp[k++] = a[j++];
            inv += m - i;              // 왼쪽에 남은 원소는 모두 a[j]보다 크다
        }
    }
    while (i < m) tmp[k++] = a[i++];
    while (j < r) tmp[k++] = a[j++];
    for (int t = 0; t < k; t++) a[l + t] = tmp[t];
    return inv;
}
"""

PWMOD = """
long long pw(long long x, long long n, long long m) {   // xⁿ mod m
    if (n == 0) return 1 % m;
    long long h = pw(x, n / 2, m);
    if (n % 2 == 0) return h * h % m;                    // 곱셈 한 번
    return h * h % m * x % m;                            // 곱셈 두 번
}
"""

MATPOW = """
// [[1, 1], [1, 0]]ⁿ = [[F(n+1), F(n)], [F(n), F(n-1)]]
typedef array<array<long long, 2>, 2> Mat;
Mat mul(Mat A, Mat B) {                // 2 × 2 곱: 원소 곱셈 8번
    Mat C{};
    for (int i = 0; i < 2; i++) for (int j = 0; j < 2; j++)
        for (int k = 0; k < 2; k++) C[i][j] += A[i][k] * B[k][j];
    return C;
}
"""

CLOSEST = """
// 점들을 x좌표 순으로 정렬해 둔다. p[l..r-1]에서 가장 가까운 거리
double solve(int l, int r) {
    if (r - l <= 3) return brute(l, r);         // 점이 적으면 모두 비교
    int m = (l + r) / 2;
    double midx = p[m].x;                       // 가운데 세로선
    double d = min(solve(l, m), solve(m, r));   // 두 반에서 각각
    // 세로선에서 x 거리가 d보다 가까운 점만 띠에 모은다
    vector<P> strip;
    for (int i = l; i < r; i++) if (fabs(p[i].x - midx) < d) strip.push_back(p[i]);
    sort(strip.begin(), strip.end(), byY);      // y좌표 순
    for (int i = 0; i < strip.size(); i++)
        for (int j = i + 1; j < strip.size() && strip[j].y - strip[i].y < d; j++)
            d = min(d, dist(strip[i], strip[j]));
    return d;
}
"""

