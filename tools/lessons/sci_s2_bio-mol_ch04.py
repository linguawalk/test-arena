def _y(bp):
    return 1 + 4 * math.log10(bp / 100)


def _lane(x, sizes, label, hl=False):
    els = [poly([(x - 0.6, 9), (x + 0.6, 9), (x + 0.6, 9.4), (x - 0.6, 9.4)]), tx((x, 10), label)]
    for b in sizes:
        y = _y(b)
        els.append(poly([(x - 0.6, y - 0.12), (x + 0.6, y - 0.12), (x + 0.6, y + 0.12), (x - 0.6, y + 0.12)], hl=hl))
    return els


