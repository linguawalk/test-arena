def _tube(x, bands):
    els = [poly([(x - 0.6, 0), (x + 0.6, 0), (x + 0.6, 5), (x - 0.6, 5)], fill=False)]
    for y in bands:
        els.append(seg((x - 0.55, y), (x + 0.55, y), hl=True))
    return els


