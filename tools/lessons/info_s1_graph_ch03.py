DIJK = """
// 다익스트라: d[v]는 시작점 s에서 v까지의 최단 거리
priority_queue<pair<long long, int>, vector<pair<long long, int>>, greater<>> pq;  // (거리, 정점), 최소 힙
fill(d, d + n + 1, INF);
d[s] = 0; pq.push({0, s});
while (!pq.empty()) {
    auto [du, u] = pq.top(); pq.pop();
    if (du > d[u]) continue;                // 이미 더 짧게 확정된 정점이면 건너뛴다
    for (auto [v, w] : adj[u])
        if (d[u] + w < d[v]) {
            d[v] = d[u] + w;
            prv[v] = u;                     // v 바로 앞의 정점
            pq.push({d[v], v});
        }
}
"""
