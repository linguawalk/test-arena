PI = """
// pi[i]: p[0..i]의 접두사이면서 접미사인 것(자기 자신 제외) 중 가장 긴 길이
vector<int> pi(m, 0);
for (int i = 1, j = 0; i < m; i++) {
    while (j > 0 && p[i] != p[j]) j = pi[j - 1];   // 더 짧은 경계로
    if (p[i] == p[j]) j++;
    pi[i] = j;
}
"""

KMP = """
int back = 0;                                   // j를 줄인 횟수
for (int i = 0, j = 0; i < n; i++) {
    while (j > 0 && t[i] != p[j]) { j = pi[j - 1]; back++; }
    if (t[i] == p[j]) {
        if (j == m - 1) { found(i - m + 1); j = pi[j]; }   // 찾았으면 경계로
        else j++;
    }
}
"""

